// Warnings for team-mode Make projects whose source has grown into one huge
// file: Make reads and saves every file whole over its filesystem socket, so a
// single large module (often inline base64 images) is slow and can time out.
// These only warn: nothing is refused and no exit code changes.

export const MAX_SOURCE_BYTES = 150 * 1024;
export const MAX_SOURCE_LINES = 1500;
export const MAX_INLINE_BASE64_BYTES = 50 * 1024;

const SOURCE = /\.(?:[cm]?[jt]sx?|css|scss|sass|less|html?|vue|svelte)$/i;
// Folders whose files are not hand-authored source: vendored libraries,
// static public/ files (themes), docs and dependencies.
const SKIPPED_FOLDERS = new Set(['vendor', 'public', 'docs', 'guidelines', 'node_modules', '.figma-cli', 'dist', 'build']);
// Asset modules: images, fonts or icons kept as code on purpose, or generated.
const ASSET_PART = /^(?:assets?|images?|img|fonts?|icons?|generated)$/i;
const ASSET_NAME = /(?:^|[.\-_])(?:assets?|images?|fonts?|icons?|generated)(?:[.\-_]|$)/i;
const GENERATED = /@generated|auto-?generated|generated by|do not edit/i;
const DATA_URI = /data:[\w.+-]+\/[\w.+-]+(?:;[\w.+-]+=[\w.+-]+)*;base64,([A-Za-z0-9+/]+={0,2})/g;
// A bare base64 run this long is an embedded file, not code.
const BARE_BASE64 = /[A-Za-z0-9+/]{1024,}={0,2}/g;

// Authored source the size rule applies to (by path alone).
export function isSizeChecked(path) {
  if (!SOURCE.test(path) || /\.d\.ts$/i.test(path) || /\.min\.(?:js|css)$/i.test(path)) return false;
  const parts = path.split('/');
  const name = parts.pop();
  return !parts.some(part => SKIPPED_FOLDERS.has(part.toLowerCase()) || ASSET_PART.test(part)) && !ASSET_NAME.test(name);
}

// Bytes of inline base64 (data: URIs and long bare runs) in a source text.
export function inlineBase64Bytes(text) {
  let total = 0;
  const rest = text.replace(DATA_URI, (_, payload) => { total += payload.length; return ''; });
  for (const run of rest.matchAll(BARE_BASE64)) total += run[0].length;
  return total;
}

const lineCount = text => (text ? text.split('\n').length - (text.endsWith('\n') ? 1 : 0) : 0);
const kb = bytes => `${Math.round(bytes / 1024).toLocaleString('en-US')} KB`;

// One finding per oversized authored source file. `files` are
// { path, bytes, content? }: without content (only sizes are known) only the
// byte size is checked. A file whose head marks it as generated is skipped.
export function sizeFindings(files, { ignored = () => false } = {}) {
  const findings = [];
  for (const file of files) {
    if (ignored(file.path) || !isSizeChecked(file.path)) continue;
    const text = file.content == null ? null : Buffer.from(file.content).toString('utf8');
    if (text != null && GENERATED.test(text.slice(0, 400))) continue;
    const bytes = file.bytes ?? Buffer.byteLength(text ?? '');
    const lines = text == null ? null : lineCount(text);
    const base64 = text == null ? null : inlineBase64Bytes(text);
    const reasons = [];
    if (bytes > MAX_SOURCE_BYTES) reasons.push('size');
    if (lines != null && lines > MAX_SOURCE_LINES) reasons.push('lines');
    if (base64 != null && base64 > MAX_INLINE_BASE64_BYTES) reasons.push('inline-base64');
    if (reasons.length) findings.push({ path: file.path, bytes, ...(lines != null ? { lines } : {}), ...(base64 != null ? { inlineBase64Bytes: base64 } : {}), reasons });
  }
  return findings.sort((a, b) => b.bytes - a.bytes || a.path.localeCompare(b.path));
}

// Plain-language warning for one finding.
export function sizeWarning(finding) {
  const facts = [kb(finding.bytes)];
  if (finding.lines != null) facts.push(`${finding.lines.toLocaleString('en-US')} lines`);
  let text = `${finding.path} is large (${facts.join(', ')})`;
  if (finding.reasons.includes('inline-base64')) text += ` and holds ${kb(finding.inlineBase64Bytes)} of inline base64 images or files`;
  const advice = [];
  if (finding.reasons.includes('size') || finding.reasons.includes('lines')) advice.push('split it into smaller modules by feature area');
  if (finding.reasons.includes('inline-base64')) advice.push('move the images to asset files');
  return `${text}. Very large files make Make slow to read and save and can time out; ${advice.join(' and ')}.`;
}

export const sizeWarnings = (files, options) => sizeFindings(files, options).map(sizeWarning);
