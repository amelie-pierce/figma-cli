import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { inlineBase64Bytes, isSizeChecked, MAX_INLINE_BASE64_BYTES, MAX_SOURCE_BYTES, MAX_SOURCE_LINES, sizeFindings, sizeWarning,
  sizeWarnings } from '../src/make-size.js';

const lines = n => Array.from({ length: n }, (_, i) => `export const v${i} = ${i};`).join('\n') + '\n';
const image = kb => `data:image/png;base64,${'iVBORw0KGgo'.repeat(Math.ceil(kb * 1024 / 11)).slice(0, kb * 1024)}`;

describe('make source size rule', () => {
  it('uses the agreed thresholds', () => {
    assert.equal(MAX_SOURCE_BYTES, 150 * 1024);
    assert.equal(MAX_SOURCE_LINES, 1500);
    assert.equal(MAX_INLINE_BASE64_BYTES, 50 * 1024);
  });

  it('checks authored source and skips vendor, public, docs, asset and generated modules', () => {
    for (const path of ['src/adc/Workspace.tsx', 'src/App.jsx', 'src/styles/index.css', 'index.html', 'src/lib/util.mjs']) {
      assert.equal(isSizeChecked(path), true, path);
    }
    for (const path of ['src/vendor/atomic-aui/lib/Table.tsx', 'public/themes/dark.css', 'docs/guide.ts', 'README.md',
      'src/assets/images.ts', 'src/images/logo.ts', 'src/fonts/inter.css', 'src/lib/icons.ts', 'src/data.generated.ts',
      'src/types.d.ts', 'src/lib/chart.min.js', 'node_modules/x/index.js', 'package.json', 'src/logo.png', 'guidelines/Guidelines.md']) {
      assert.equal(isSizeChecked(path), false, path);
    }
  });

  it('counts data URIs and long bare base64 runs, not ordinary code', () => {
    assert.equal(inlineBase64Bytes(`const a = "${image(2)}";`), 2048);
    assert.equal(inlineBase64Bytes(`const b = "${'QUJD'.repeat(512)}";`), 2048);
    assert.equal(inlineBase64Bytes(lines(200)), 0);
    assert.equal(inlineBase64Bytes('const short = "data:image/svg+xml;base64,PHN2Zz4=";'), 'PHN2Zz4='.length);
  });

  it('warns on size, line count and inline base64 with plain advice', () => {
    const findings = sizeFindings([
      { path: 'src/adc/Workspace.tsx', content: Buffer.from(`${lines(1600)}const hero = "${image(60)}";\n`) },
      { path: 'src/small.tsx', content: Buffer.from(lines(20)) },
      { path: 'src/vendor/lib/Huge.tsx', content: Buffer.from(lines(5000)) },
    ]);
    assert.deepEqual(findings.map(f => [f.path, f.reasons]), [['src/adc/Workspace.tsx', ['lines', 'inline-base64']]]);
    const [warning] = findings.map(sizeWarning);
    assert.match(warning, /^src\/adc\/Workspace\.tsx is large \(\d+ KB, 1,601 lines\) and holds 60 KB of inline base64/);
    assert.match(warning, /split it into smaller modules by feature area and move the images to asset files\.$/);
  });

  it('checks only the byte size when content is unknown, and skips ignored and generated files', () => {
    assert.deepEqual(sizeWarnings([{ path: 'src/Big.tsx', bytes: 200 * 1024 }, { path: 'src/Ok.tsx', bytes: 10 * 1024 }]),
      ['src/Big.tsx is large (200 KB). Very large files make Make slow to read and save and can time out; split it into smaller modules by feature area.']);
    assert.deepEqual(sizeWarnings([{ path: 'src/Big.tsx', bytes: 200 * 1024 }], { ignored: path => path === 'src/Big.tsx' }), []);
    assert.deepEqual(sizeWarnings([{ path: 'src/table.ts', content: Buffer.from(`// @generated by build-icons\n${lines(3000)}`) }]), []);
  });

  it('suggests only moving images when the file is otherwise small', () => {
    const [warning] = sizeWarnings([{ path: 'src/Hero.tsx', content: Buffer.from(`export const src = "${image(55)}";\n`) }]);
    assert.match(warning, /holds 55 KB of inline base64.*; move the images to asset files\.$/);
  });
});
